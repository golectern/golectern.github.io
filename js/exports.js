/* Lectern — exports: quiz results (Excel / printable PDF), attendance, annotated lesson PDF */
(function (H) {
  'use strict';
  const { t } = H;
  const safe = (s) => String(s || 'export').replace(/[\\/:*?"<>|]+/g, ' ').trim().slice(0, 60) || 'export';
  const optLetter = (i) => String.fromCharCode(65 + i);

  function answerText(q) {
    if (q.type === 'order' && q.options) return q.options.map((o) => (typeof o === 'string' ? o : o.text)).join(' → ');
    if (['mcq', 'tf'].includes(q.type) && q.options && q.options[q.correct] != null) return optLetter(q.correct) + '. ' + q.options[q.correct];
    return '';
  }

  /** Per-question statistics from a saved result */
  function itemAnalysis(r) {
    return r.questions.map((q, i) => {
      const ans = r.people.map((p) => p.answers[i]).filter(Boolean);
      const scored = ans.some((a) => a.ok === true || a.ok === false) || ['mcq', 'tf'].includes(q.type);
      const right = ans.filter((a) => a.ok === true).length;
      const wrong = {};
      ans.filter((a) => a.ok === false).forEach((a) => { const k = String(a.v).trim().toLowerCase(); (wrong[k] = wrong[k] || { v: a.v, n: 0 }).n++; });
      const top = Object.values(wrong).sort((a, b) => b.n - a.n)[0];
      const times = ans.map((a) => a.time).filter((x) => typeof x === 'number');
      const away = ans.reduce((s, a) => s + (a.away || 0), 0);
      return { n: i + 1, text: q.text, type: q.type, answered: ans.length, of: r.people.length,
        pct: scored && r.people.length ? Math.round(right / r.people.length * 100) : null,
        topWrong: top ? `${top.v} (${top.n})` : '', avgTime: times.length ? Math.round(times.reduce((a, b) => a + b, 0) / times.length * 10) / 10 : null, away };
    });
  }

  H.exports = {
    itemAnalysis,
    async resultsXlsx(r) {
      if (!r) return;
      const X = await H.need.xlsx();
      const wb = X.utils.book_new();
      const away = r.people.some((p) => p.away);
      const teams = r.people.some((p) => p.team);
      const head = ['Rank', 'Name', 'Score', 'Correct', 'Incorrect'].concat(teams ? ['Team'] : [], away ? ['Left the quiz screen'] : [], r.questions.map((q, i) => 'Q' + (i + 1)));
      const rows = [head].concat(r.people.map((p) => [p.rank, p.name, p.score, p.correct, p.incorrect].concat(teams ? [p.team || ''] : [], away ? [p.away || 0] : [], p.answers.map((a) => (a ? (a.ok === true ? '✓ ' : a.ok === false ? '✗ ' : '') + a.v + (a.score ? ` (+${a.score})` : '') : '')))));
      const ws = X.utils.aoa_to_sheet(rows);
      ws['!cols'] = head.map((c, i) => ({ wch: i === 1 ? 24 : i < 5 ? 9 : 22 }));
      X.utils.book_append_sheet(wb, ws, 'Results');
      const qrows = [['#', 'Type', 'Question', 'Correct answer', 'Responses', 'Average', 'Source']];
      r.questions.forEach((q, i) => {
        let resp = '';
        if (q.counts) resp = q.type === 'scale' ? q.counts.map((c, k) => `${k + 1}: ${c}`).join('  ') : q.options.map((o, k) => `${optLetter(k)}. ${o}: ${q.counts[k] || 0}`).join('  |  ');
        if (q.words) resp = q.words.join(', ');
        if (q.ideas) resp = q.ideas.map((x) => `${x.text} — ${x.by} (❤${x.reactions})`).join('  |  ');
        qrows.push([i + 1, q.type, q.text, answerText(q), resp, q.type === 'scale' ? (q.avg || 0).toFixed(2) : '', q.source || '']);
      });
      const qs = X.utils.aoa_to_sheet(qrows);
      qs['!cols'] = [{ wch: 4 }, { wch: 8 }, { wch: 50 }, { wch: 24 }, { wch: 70 }, { wch: 8 }, { wch: 24 }];
      X.utils.book_append_sheet(wb, qs, 'Questions');
      const ia = itemAnalysis(r);
      const iaS = X.utils.aoa_to_sheet([['#', 'Question', 'Type', 'Answered', '% correct (of all students)', 'Most-chosen wrong answer (count)', 'Average time (s)']]
        .concat(ia.map((x) => [x.n, x.text, x.type, `${x.answered}/${x.of}`, x.pct == null ? '' : x.pct + '%', x.topWrong, x.avgTime == null ? '' : x.avgTime])));
      iaS['!cols'] = [{ wch: 4 }, { wch: 50 }, { wch: 8 }, { wch: 10 }, { wch: 14 }, { wch: 34 }, { wch: 12 }];
      X.utils.book_append_sheet(wb, iaS, 'Item analysis');
      const info = X.utils.aoa_to_sheet([['Quiz', r.title], ['Subject', r.subject || ''], ['Lesson', r.lesson || ''], ['Date', new Date(r.at).toLocaleString()], ['Participants', r.people.length], ['Generated by', 'Lectern']]);
      info['!cols'] = [{ wch: 14 }, { wch: 50 }];
      X.utils.book_append_sheet(wb, info, 'Info');
      X.writeFile(wb, `${safe(r.title)} - results.xlsx`);
    },

    /** Opens the print dialog with a clean report — choose "Save as PDF". Works with Kurdish/Arabic text. */
    resultsPdf(r) {
      if (!r) return;
      const e = H.esc;
      const d = new Date(r.at);
      const medal = ['🥇', '🥈', '🥉'];
      const html = `<!doctype html><html><head><meta charset="utf-8"><title>${e(r.title)} - results</title><style>
        @page{size:A4;margin:14mm}body{font-family:"Segoe UI",Tahoma,"Noto Naskh Arabic",system-ui,sans-serif;color:#111827;font-size:12px}
        h1{font-size:22px;margin:0 0 4px}h2{font-size:15px;margin:22px 0 8px;border-bottom:2px solid #e5e7eb;padding-bottom:4px}
        .meta{color:#6b7280;margin-bottom:12px}.meta b{color:#111827}table{width:100%;border-collapse:collapse}
        th,td{border:1px solid #e5e7eb;padding:6px 8px;text-align:start;vertical-align:top}th{background:#f3f4f6}
        .lb{display:flex;gap:10px;flex-wrap:wrap}.lb div{border:1px solid #e5e7eb;border-radius:10px;padding:8px 12px;min-width:120px}
        .q{margin:8px 0;padding:8px 10px;border:1px solid #e5e7eb;border-radius:8px;page-break-inside:avoid}.ok{color:#059669;font-weight:600}
        .foot{margin-top:24px;color:#9ca3af;font-size:10px;text-align:center}[dir=auto]{unicode-bidi:plaintext}
      </style></head><body>
      <h1 dir="auto">${e(r.title)}</h1>
      <div class="meta">${r.subject ? `Subject: <b dir="auto">${e(r.subject)}</b> · ` : ''}Date: <b>${d.toLocaleDateString()}</b> · Time: <b>${d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}</b> · Participants: <b>${r.people.length}</b></div>
      <h2>🏆 Leaderboard</h2><div class="lb">${r.people.slice(0, 3).map((p, i) => `<div>${medal[i]} <b dir="auto">${e(p.name)}</b><br>${p.score} pts · ${p.correct} correct</div>`).join('') || 'No participants.'}</div>
      ${r.teams ? `<h2>👥 Teams</h2><table><tr><th>Team</th><th>Members</th><th>Average score</th></tr>${r.teams.map((x) => `<tr><td>${e(x.label)}</td><td>${x.members}</td><td>${x.score}</td></tr>`).join('')}</table>` : ''}
      <h2>📊 Results</h2><table><tr><th>#</th><th>Name</th><th>Score</th><th>Correct</th><th>Incorrect</th><th>Note</th></tr>
      ${r.people.map((p) => `<tr><td>${p.rank}</td><td dir="auto">${e(p.emoji || '')} ${e(p.name)}</td><td>${p.score}</td><td>${p.correct}</td><td>${p.incorrect}</td><td>${p.away ? `⚠️ left screen ${p.away}×` : ''}</td></tr>`).join('')}</table>
      <h2>🔎 Item analysis</h2><table><tr><th>#</th><th>Question</th><th>Answered</th><th>% correct</th><th>Most-chosen wrong answer</th><th>Avg time</th></tr>
      ${itemAnalysis(r).map((x) => `<tr><td>${x.n}</td><td dir="auto">${e(x.text)}</td><td>${x.answered}/${x.of}</td><td>${x.pct == null ? '—' : x.pct + '%'}</td><td dir="auto">${e(x.topWrong)}</td><td>${x.avgTime == null ? '—' : x.avgTime + ' s'}</td></tr>`).join('')}</table>
      <h2>📋 Questions</h2>${r.questions.map((q, i) => `<div class="q"><b>${i + 1}.</b> <span dir="auto">${e(q.text)}</span>
        ${q.options && q.options.length && q.type !== 'scale' ? `<div>${q.options.map((o, k) => `<span class="${k === q.correct && q.type !== 'poll' ? 'ok' : ''}">${optLetter(k)}. <span dir="auto">${e(o)}</span>${q.counts ? ` (${q.counts[k] || 0})` : ''}</span>`).join(' &nbsp; ')}</div>` : ''}
        ${answerText(q) ? `<div class="ok">✓ Correct answer: <span dir="auto">${e(answerText(q))}</span></div>` : ''}
        ${q.type === 'scale' ? `<div>Average: <b>${(q.avg || 0).toFixed(2)}</b></div>` : ''}
        ${q.words ? `<div dir="auto">${e(q.words.join(', '))}</div>` : ''}
        ${q.ideas ? q.ideas.map((x) => `<div dir="auto">💡 ${e(x.text)} — <i>${e(x.by)}</i> (❤ ${x.reactions})</div>`).join('') : ''}
        ${q.source ? `<div style="color:#6b7280">📖 ${e(q.source)}</div>` : ''}</div>`).join('') || 'No questions.'}
      <div class="foot">Generated by Lectern</div></body></html>`;
      printHtml(html);
    },

    /** Printable question paper (withKey = answer key) for a quiz */
    quizPaper(q, withKey) {
      const e = H.esc;
      const L = (i) => String.fromCharCode(65 + i);
      const item = (x, i) => {
        let body = '';
        if (x.type === 'order') body = withKey ? `<div class="key">✓ <span dir="auto">${e(x.options.map((o) => o.text).join(' → '))}</span></div>` : `<div class="opts">${x.options.map((o, k) => ({ o, k })).sort((a, b) => ((a.k * 7 + 3) % x.options.length) - ((b.k * 7 + 3) % x.options.length)).map(({ o }) => `<div><span class="box"></span> <span dir="auto">${e(o.text)}</span></div>`).join('')}</div><div class="src">Number the boxes 1–${x.options.length} in the right order.</div>`;
        else if (['mcq', 'tf', 'poll'].includes(x.type)) body = `<ol class="opts">${(x.options || []).map((o, k) => `<li class="${withKey && x.type !== 'poll' && k === x.correct ? 'key' : ''}"><span class="box">${withKey && x.type !== 'poll' && k === x.correct ? '✓' : ''}</span> <b>${L(k)}.</b> <span dir="auto">${e(o.text)}</span></li>`).join('')}</ol>`;
        else if (x.type === 'scale') body = `<div class="scale">${Array.from({ length: x.scaleMax || 5 }, (_, k) => `<span class="box"></span> ${k + 1}`).join(' &nbsp; ')}</div>`;
        else if (withKey && x.type === 'open' && x.accept) body = `<div class="key">✓ <span dir="auto">${e(x.accept)}</span></div>`;
        else body = '<div class="lines"></div>';
        return `<div class="q"><div class="qt"><b>${i + 1}.</b> <span dir="auto">${e(x.text)}</span>${x.points && !withKey ? ` <span class="pts">(${x.points} pts)</span>` : ''}</div>
          ${x.image ? `<img src="${e(x.image)}" alt="">` : ''}${body}${withKey && x.source ? `<div class="src">📖 ${e(x.source)}</div>` : ''}</div>`;
      };
      const html = `<!doctype html><html><head><meta charset="utf-8"><title>${e(q.title || 'Quiz')}${withKey ? ' - answer key' : ''}</title><style>
        @page{size:A4;margin:16mm}body{font-family:"Segoe UI",Tahoma,"Noto Naskh Arabic",system-ui,sans-serif;color:#111827;font-size:13px}
        h1{font-size:21px;margin:0 0 4px}.meta{color:#6b7280;margin-bottom:10px}.who{display:flex;gap:30px;margin:10px 0 16px}.who span{flex:1;border-bottom:1px solid #9ca3af;padding-bottom:2px}
        .q{margin:0 0 14px;page-break-inside:avoid}.qt{font-weight:600;margin-bottom:6px}.pts{color:#6b7280;font-weight:400}
        .opts{list-style:none;padding:0;margin:0 0 0 18px}.opts li{margin:3px 0}.box{display:inline-block;width:13px;height:13px;border:1.5px solid #374151;border-radius:3px;vertical-align:-2px;text-align:center;line-height:12px;font-size:11px}
        .key{color:#047857;font-weight:700}.opts li.key .box{background:#047857;color:#fff;border-color:#047857}.lines{height:46px;background:repeating-linear-gradient(transparent 0 22px,#d1d5db 22px 23px)}
        .src{color:#6b7280;font-size:11px;margin-top:3px}img{max-width:60%;max-height:160px;display:block;margin:4px 0}[dir=auto]{unicode-bidi:plaintext}
        .badge{display:inline-block;background:#047857;color:#fff;border-radius:6px;padding:1px 8px;font-size:12px;margin-inline-start:8px}</style></head><body>
        <h1 dir="auto">${e(q.title || 'Quiz')}${withKey ? '<span class="badge">ANSWER KEY</span>' : ''}</h1>
        <div class="meta">${q.subject ? `<b dir="auto">${e(q.subject)}</b> · ` : ''}${(q.questions || []).length} questions</div>
        ${withKey ? '' : '<div class="who"><span>Name:</span><span>Group / ID:</span><span>Date:</span></div>'}
        ${(q.questions || []).map(item).join('')}</body></html>`;
      printHtml(html);
    },

    /** One printable page per student: their answers, right/wrong, correct answers */
    studentReports(r) {
      if (!r) return;
      const e = H.esc;
      const d = new Date(r.at);
      const page = (p) => `<section class="pg"><h1 dir="auto">${e(r.title)}</h1>
        <div class="meta">${r.subject ? `<b dir="auto">${e(r.subject)}</b> · ` : ''}${d.toLocaleDateString()} · ${d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}</div>
        <div class="who"><b dir="auto">${e(p.emoji || '')} ${e(p.name)}</b> — Score <b>${p.score}</b> · Rank <b>${p.rank}/${r.people.length}</b> · Correct <b>${p.correct}</b> · Incorrect <b>${p.incorrect}</b>${p.away ? ` · ⚠️ Left the quiz screen <b>${p.away}</b>×` : ''}</div>
        <table><tr><th>#</th><th>Question</th><th>Your answer</th><th></th><th>Correct answer</th><th>Points</th></tr>
        ${r.questions.map((q, i) => { const a = p.answers[i]; return `<tr><td>${i + 1}</td><td dir="auto">${e(q.text)}</td><td dir="auto">${a ? e(a.v) : '—'}</td><td>${a && a.ok === true ? '✅' : (a && a.ok === false) || (!a && ['mcq', 'tf'].includes(q.type)) ? '❌' : ''}</td><td dir="auto">${e(answerText(q) || (q.type === 'open' && q.accept ? q.accept : ''))}</td><td>${a && a.score ? a.score : 0}</td></tr>`; }).join('')}</table></section>`;
      const html = `<!doctype html><html><head><meta charset="utf-8"><title>${e(r.title)} - student reports</title><style>
        @page{size:A4;margin:14mm}body{font-family:"Segoe UI",Tahoma,"Noto Naskh Arabic",system-ui,sans-serif;color:#111827;font-size:12px}
        .pg{page-break-after:always}.pg:last-child{page-break-after:auto}h1{font-size:20px;margin:0 0 4px}.meta{color:#6b7280;margin-bottom:8px}
        .who{font-size:14px;margin:8px 0 12px;padding:8px 10px;background:#f3f4f6;border-radius:8px}
        table{width:100%;border-collapse:collapse}th,td{border:1px solid #e5e7eb;padding:5px 7px;text-align:start;vertical-align:top}th{background:#f9fafb}
        [dir=auto]{unicode-bidi:plaintext}</style></head><body>${r.people.map(page).join('') || 'No participants.'}</body></html>`;
      printHtml(html);
    },

    async attendanceXlsx(r) {
      const X = await H.need.xlsx();
      const rows = [['#', 'Name', 'Joined', 'Last seen', 'Still connected at export']].concat((r.people || []).map((p, i) => [i + 1, p.name, new Date(p.joinedAt).toLocaleTimeString(), p.lastSeen ? new Date(p.lastSeen).toLocaleTimeString() : '', p.online ? 'yes' : 'no']));
      const ws = X.utils.aoa_to_sheet([[r.title], ['Date', new Date(r.at).toLocaleString()], []].concat(rows));
      ws['!cols'] = [{ wch: 5 }, { wch: 28 }, { wch: 12 }, { wch: 12 }, { wch: 22 }];
      const wb = X.utils.book_new();
      X.utils.book_append_sheet(wb, ws, 'Attendance');
      X.writeFile(wb, `${safe(r.title)}.xlsx`);
    },

    /** Lesson with drawings → PDF file (one page per slide) */
    async lessonPdf(lesson) {
      H.toast(t('preparing'));
      const jsPDF = await H.need.jspdf();
      let pdf = null;
      for (const it of lesson.items) {
        const aspect = it.w && it.h ? it.w / it.h : 16 / 9;
        const W = 1600, Hh = Math.round(W / aspect);
        const c = document.createElement('canvas'); c.width = W; c.height = Hh;
        const x = c.getContext('2d');
        x.fillStyle = it.type === 'board' && it.bg === 'black' ? '#111' : '#fff'; x.fillRect(0, 0, W, Hh);
        if (it.type === 'image') {
          const u = await H.store.blobUrl(it.blobId);
          const img = new Image(); img.src = u;
          try { await img.decode(); x.drawImage(img, 0, 0, W, Hh); } catch (e) { /* skip broken image */ }
        } else if (it.type === 'board' && it.bg === 'grid') {
          x.strokeStyle = '#e5e7eb'; x.lineWidth = 1;
          for (let gx = 0; gx < W; gx += 40) { x.beginPath(); x.moveTo(gx, 0); x.lineTo(gx, Hh); x.stroke(); }
          for (let gy = 0; gy < Hh; gy += 40) { x.beginPath(); x.moveTo(0, gy); x.lineTo(W, gy); x.stroke(); }
        } else if (it.type !== 'board') {
          x.fillStyle = '#111827'; x.font = '600 54px "Segoe UI", system-ui, sans-serif'; x.textAlign = 'center';
          x.fillText(H.ui.typeIcon(it) + ' ' + (it.title || ''), W / 2, Hh / 2, W - 120);
          if (it.url) { x.font = '32px system-ui'; x.fillStyle = '#6b7280'; x.fillText(it.url, W / 2, Hh / 2 + 60, W - 120); }
        }
        const ops = (lesson.ink || {})[it.uid];
        if (ops && ops.length) ops.forEach((o) => H.ink.drawOp(x, o, W, Hh));
        const img = c.toDataURL('image/jpeg', 0.85);
        const pw = 297, ph = 297 / aspect;
        if (!pdf) pdf = new jsPDF({ orientation: pw >= ph ? 'landscape' : 'portrait', unit: 'mm', format: [pw, ph] });
        else pdf.addPage([pw, ph], pw >= ph ? 'landscape' : 'portrait');
        pdf.addImage(img, 'JPEG', 0, 0, pw, ph);
      }
      if (pdf) pdf.save(`${safe(lesson.title)}.pdf`);
    },
  };

  function printHtml(html) {
    const f = document.createElement('iframe');
    Object.assign(f.style, { position: 'fixed', right: 0, bottom: 0, width: 0, height: 0, border: 0 });
    document.body.appendChild(f);
    const d = f.contentWindow.document;
    d.open(); d.write(html); d.close();
    setTimeout(() => { f.contentWindow.focus(); f.contentWindow.print(); setTimeout(() => f.remove(), 60000); }, 350);
  }
})(window.Hub);
